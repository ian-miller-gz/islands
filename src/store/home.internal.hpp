#pragma once
#include <filesystem>

#include <common.hpp>

namespace STORE::HOME {
inline constexpr STRING::Hot LEAF = "/islands/store";

inline auto directory() -> String {
  const String data = COMMON::PLATFORM::data();
  if (!data.empty()) return data + LEAF;
  std::error_code slip;
  return std::filesystem::temp_directory_path(slip).string() + LEAF;
}
}  // namespace STORE::HOME
